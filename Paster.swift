import Cocoa

/// Puts text on the clipboard and posts Cmd+V so it lands wherever the
/// user's text cursor is (Terminal, browsers, editors, etc.), then restores
/// the previous clipboard contents.
final class Paster {
    private let restoreDelay: TimeInterval = 1.2

    func paste(_ text: String) {
        let pasteboard = NSPasteboard.general
        let expectedChangeCount = pasteboard.changeCount
        let previousString = pasteboard.string(forType: .string)

        let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
        let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
        let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
        let legacyTransientType = NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType")

        pasteboard.declareTypes([.string, transientType, concealedType, autoGeneratedType, legacyTransientType], owner: nil)
        pasteboard.setString(text, forType: .string)
        pasteboard.setString("", forType: transientType)
        pasteboard.setString("", forType: concealedType)
        pasteboard.setString("", forType: autoGeneratedType)
        pasteboard.setString("", forType: legacyTransientType)

        let source = CGEventSource(stateID: .hidSystemState)
        let keyDown = CGEvent(keyboardEventSource: source, virtualKey: 9, keyDown: true) // 9 = 'v'
        keyDown?.flags = .maskCommand
        keyDown?.post(tap: .cgSessionEventTap)
        let keyUp = CGEvent(keyboardEventSource: source, virtualKey: 9, keyDown: false)
        keyUp?.flags = .maskCommand
        keyUp?.post(tap: .cgSessionEventTap)

        // Restore the previous clipboard after the target app has consumed it.
        DispatchQueue.main.asyncAfter(deadline: .now() + restoreDelay) {
            let pb = NSPasteboard.general
            let stillHoldsTranscript = pb.string(forType: .string) == text
            guard pb.changeCount == expectedChangeCount || stillHoldsTranscript else { return }
            pb.clearContents()
            if let previousString = previousString {
                pb.setString(previousString, forType: .string)
            }
        }
    }
}
